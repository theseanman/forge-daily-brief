"""
FORGE planner + evening debrief installer  (v3 - July 23, 2026)

Fixes the silent alarm, adds seven choosable sounds, estimate-vs-actual
tracking, keystone hit rate, an off-day counter, and makes the Reminders
sync MIRROR your list instead of only ever adding to it.

    cd ~/Desktop/forge-daily-brief
    git checkout gh-pages
    git pull
    python3 forge_install3.py
"""
import base64, gzip, hashlib, json, os, shutil, sys, datetime

EXPECTED_SHA = "aceecd5ff0456b7fa9a391f7e36c93dcdf9093a34c9ff867a5b92a23fb86d703"
TARGETS = ["planner.html", "forge-evening-debrief.html"]

def fail(msg):
    print("\n  FAILED: " + msg)
    print("  Nothing was changed.")
    sys.exit(1)

def main():
    missing = [t for t in TARGETS if not os.path.exists(t)]
    if missing:
        fail("cannot find %s here. Are you in the repo folder, on gh-pages?" % ", ".join(missing))
    print("Decoding payload...")
    try:
        raw = gzip.decompress(base64.b64decode("".join(PAYLOAD.split())))
    except Exception as e:
        fail("payload corrupted during paste (%s). Re-copy and try again." % e)
    got = hashlib.sha256(raw).hexdigest()
    if got != EXPECTED_SHA:
        fail("checksum mismatch - the paste was truncated.\n  expected " + EXPECTED_SHA + "\n  got      " + got)
    print("  checksum OK")
    files = json.loads(raw.decode("utf-8"))
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    for name in TARGETS:
        shutil.copy(name, name + ".backup-" + stamp)
        print("  backed up %s" % name)
    for name in TARGETS:
        c = files[name]
        if "<script>" not in c or "</script>" not in c:
            fail("%s looks malformed" % name)
        open(name, "w", encoding="utf-8").write(c)
        print("  wrote %s (%d characters)" % (name, len(c)))
    print("\n  DONE. Both files replaced.")
    print("\nNext:")
    print("  rm forge_install3.py")
    print("  git reset")
    print("  git add planner.html forge-evening-debrief.html")
    print('  git commit -m "Alarm sounds, estimate tracking, keystone rate, mirror sync"')
    print("  git push origin gh-pages")

