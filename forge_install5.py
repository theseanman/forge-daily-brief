CREATE  = ["content/health_history.json"]

def fail(msg):
    print("\n  FAILED: " + msg)
    print("  Nothing was changed.")
    sys.exit(1)

def main():
    missing = [t for t in REPLACE if not os.path.exists(t)]
    if missing:
        fail("cannot find %s here. Are you in the repo folder, on gh-pages?" % ", ".join(missing))

    print("Decoding payload...")
    try:
        raw = gzip.decompress(base64.b64decode("".join(PAYLOAD.split())))
    except Exception as e:
        fail("payload corrupted during paste (%s). Re-copy and try again." % e)
    if hashlib.sha256(raw).hexdigest() != EXPECTED_SHA:
        fail("checksum mismatch - the paste was truncated.")
    print("  checksum OK")

    files = json.loads(raw.decode("utf-8"))
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")

    for name in REPLACE:
        shutil.copy(name, name + ".backup-" + stamp)
        print("  backed up %s" % name)

    for name in REPLACE:
        c = files[name]
        tmp = name + ".new"
        open(tmp, "w", encoding="utf-8").write(c)
        if name.endswith(".py"):
            try:
                py_compile.compile(tmp, doraise=True)
            except Exception as e:
                os.remove(tmp)
                fail("%s does not compile (%s)" % (name, e))
        elif "<script>" not in c:
            os.remove(tmp)
            fail("%s looks malformed" % name)
        os.replace(tmp, name)
        print("  wrote %s (%d chars)" % (name, len(c)))

    for name in CREATE:
        d = os.path.dirname(name)
        if d and not os.path.isdir(d):
            os.makedirs(d)
        json.loads(files[name])
        open(name, "w", encoding="utf-8").write(files[name])
        print("  wrote %s (%d chars)" % (name, len(files[name])))

    print("\n  DONE. All four files written and verified.")
    print("\nNext:")
    print("  rm -f forge_install4.py forge_install5.py")
    print("  git reset")
    print("  git add planner.html forge-evening-debrief.html forge_actions.py content/health_history.json")
    print('  git commit -m "Subscribed calendars reach the planner; dedupe; loud failures; daily record"')
    print("  git push origin gh-pages")
    print("\nTHEN: Actions tab -> Generate FORGE OS Daily Brief -> Run workflow (gh-pages).")
    print("forge_actions.py changed, so the brief must regenerate for the calendar fix to show.")

