def main():
    here = os.getcwd()
    if not os.path.exists(os.path.join(here, "forge_actions.py")):
        sys.exit("STOP: run this from ~/Desktop/forge-daily-brief (forge_actions.py not found here). Nothing written.")
    staged = {}
    for name, spec in FILES.items():
        try:
            raw = gzip.decompress(base64.b64decode(spec["data"].replace("\n", "")))
        except Exception as e:
            sys.exit(f"STOP: payload for {name} is corrupt ({e}). Paste was truncated. Nothing written.")
        got = hashlib.sha256(raw).hexdigest()
        if got != spec["sha256"]:
            sys.exit(f"STOP: checksum mismatch for {name}\n  expected {spec['sha256']}\n  got      {got}\nPaste was truncated or altered. Nothing written.")
        if len(raw) != spec["size"]:
            sys.exit(f"STOP: size mismatch for {name} (expected {spec['size']}, got {len(raw)}). Nothing written.")
        staged[name] = raw
    for name, raw in staged.items():
        if os.path.exists(name):
            bak = name + ".bak-jul24"
            os.replace(name, bak)
            print(f"backed up {name} -> {bak}")
        with open(name, "wb") as f:
            f.write(raw)
        print(f"wrote {name} ({len(raw)} bytes, sha256 verified)")
    print()
    print("DONE. Now: git pull --rebase && git add -A && git commit -m 'jul24: goal/protocol merge + models library' && git push")
    print("Then trigger the workflow — forge_actions.py changed.")

if __name__ == "__main__":
    main()
