#!/usr/bin/env python3
"""
FORGE OS installer - rewrites forge_actions.py with the July 2026 redesign.

Run it from inside your repo folder:
    cd ~/Desktop/forge-daily-brief
    git checkout gh-pages
    git pull
    python3 forge_install.py

It backs up the current file, verifies the payload, checks the result compiles,
and refuses to write anything if a single check fails.
"""
import base64, gzip, hashlib, os, shutil, sys, py_compile, datetime

EXPECTED_SHA = "d8f0723238bf7c3ffdbc496753ea8284e52fad17f440d0640915feef0dfad570"
TARGET = "forge_actions.py"

def fail(msg):
    print("\n  FAILED: " + msg)
    print("  Nothing was changed.")
    sys.exit(1)

def main():
    if not os.path.exists(TARGET):
        fail("no %s here. Are you in the repo folder?" % TARGET)

    print("Decoding payload...")
    try:
        blob = base64.b64decode("".join(PAYLOAD.split()))
        source = gzip.decompress(blob).decode("utf-8")
    except Exception as e:
        fail("payload corrupted during paste (%s). Re-copy the file and try again." % e)

    got = hashlib.sha256(source.encode("utf-8")).hexdigest()
    if got != EXPECTED_SHA:
        fail("checksum mismatch - the paste was truncated.\n"
             "  expected " + EXPECTED_SHA + "\n  got      " + got)
    print("  checksum OK (%d bytes)" % len(source))

    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = TARGET + ".backup-" + stamp
    shutil.copy(TARGET, backup)
    print("  backed up existing file to " + backup)

    tmp = TARGET + ".new"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(source)
    try:
        py_compile.compile(tmp, doraise=True)
    except Exception as e:
        os.remove(tmp)
        fail("the new file does not compile (%s)" % e)
    print("  new file compiles cleanly")

    os.replace(tmp, TARGET)
    print("\n  DONE. %s replaced." % TARGET)

    missing = [n for n in ("japanese","colonel","models","strategy","sports_facts")
               if not os.path.exists(os.path.join("content", n + ".json"))]
    if missing:
        print("  NOTE: content files not found locally: " + ", ".join(missing))
        print("        (fine if you have not pulled them yet - they are on gh-pages)")
    else:
        print("  All five content files present.")
    print("\nNext:")
    print("  git add forge_actions.py")
    print('  git commit -m "Morning OS redesign: external content pools"')
    print("  git push origin gh-pages")

