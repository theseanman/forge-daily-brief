#!/usr/bin/env python3
"""
FORGE planner + evening debrief installer  (July 23, 2026)

Adds: work-session timer, minutes + done-when fields, backlog moved to the bottom.

Run it from inside your repo folder:
    cd ~/Desktop/forge-daily-brief
    git checkout gh-pages
    git pull
    python3 forge_install2.py

It backs up both existing files, verifies the payload against a checksum, and
refuses to write anything if a single check fails.
"""
import base64, gzip, hashlib, json, os, shutil, sys, datetime

EXPECTED_SHA = "249dd1cf602a68305e5d8c63d05b5a83700fe2d7c87628278cc0208ec0979afc"
TARGETS = ["planner.html", "forge-evening-debrief.html"]

def fail(msg):
    print("\n  FAILED: " + msg)
    print("  Nothing was changed.")
    sys.exit(1)

def main():
    missing = [t for t in TARGETS if not os.path.exists(t)]
    if missing:
        fail("cannot find %s here. Are you in the repo folder, on gh-pages?" % ", ".join(missing))

    print("Decoding payload...")
    try:
        blob = base64.b64decode("".join(PAYLOAD.split()))
        raw = gzip.decompress(blob)
    except Exception as e:
        fail("payload corrupted during paste (%s). Re-copy the file and try again." % e)

    got = hashlib.sha256(raw).hexdigest()
    if got != EXPECTED_SHA:
        fail("checksum mismatch - the paste was truncated.\n"
             "  expected " + EXPECTED_SHA + "\n  got      " + got)
    print("  checksum OK")

    files = json.loads(raw.decode("utf-8"))
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")

    for name in TARGETS:
        backup = name + ".backup-" + stamp
        shutil.copy(name, backup)
        print("  backed up %s -> %s" % (name, backup))

    for name in TARGETS:
        content = files[name]
        if "<script>" not in content or "</script>" not in content:
            fail("%s looks malformed - no script block found" % name)
        with open(name, "w", encoding="utf-8") as fh:
            fh.write(content)
        print("  wrote %s (%d characters)" % (name, len(content)))

    print("\n  DONE. Both files replaced.")
    print("\nNext:")
    print("  git add planner.html forge-evening-debrief.html")
    print('  git commit -m "Work session timer, done-when fields, backlog to bottom"')
    print("  git push origin gh-pages")
    print("\nNo workflow trigger needed - neither file is generated.")

